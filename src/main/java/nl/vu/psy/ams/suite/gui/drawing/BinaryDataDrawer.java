	private void drawAv(Graphics2D g) {
		if (av == null)
			return;
		g.setColor(avColor);
		Stroke oldStroke = g.getStroke();
		g.setStroke(new BasicStroke(2));

		double leftTime = graph.getxAxis().getLeftTime();
		double rightTime = graph.getxAxis().getRightTime();

		int w = graph.getWidth();
		int h = graph.getHeight();

		AffineTransform at = new AffineTransform();
		at.scale(w / (rightTime - leftTime), -h / (yAxis.getTopValue() - yAxis.getBottomValue()));
		at.translate(-leftTime, -yAxis.getTopValue());

		int nPointsInPath = 0;
		double curTime = CurrentOpenData.getInstance().getStartTimeInUS() + avLength / 2;
		int n = av.length;
		Path2D.Double path = new Path2D.Double(Path2D.WIND_EVEN_ODD, n);
		int li = (int) ((leftTime - CurrentOpenData.getInstance().getStartTimeInUS()) / avLength);
		if (li < 0)
			li = 0;
		curTime += li * avLength;
		for (int i = li; i < n; i++) {
			if (curTime > rightTime + avLength)
				break;
			if (curTime > leftTime - avLength) {
				// double val = csi.splint(curTime);
				double val = av[i];
				if (clipAtZero && yAxis.getRealValueFromSampleValue(val) < 0)
					val = yAxis.getSampleValueFromRealValue(0);
				if (nPointsInPath == 0) {
					path.moveTo(curTime, val);
				} else {
					path.lineTo(curTime, val);
				}
				nPointsInPath++;
			}
			curTime += avLength;
		}
		if (nPointsInPath > 0) {
			path.transform(at);
			g.draw(path);
		}
		g.setStroke(oldStroke);
	}

