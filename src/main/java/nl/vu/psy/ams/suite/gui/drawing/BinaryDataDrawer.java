				if (channelName.equals("MYA")) {
					minValue = yAxis.getSampleValueFromRealValue(
							CurrentOpenData.getInstance().getDebugSettings().getMotilityRawMin());
					maxValue = yAxis.getSampleValueFromRealValue(
							CurrentOpenData.getInstance().getDebugSettings().getMotilityRawMax());
					// if(retArray[0] < minValue){
					retArray[0] = minValue;
					// }
					// if(retArray[1] > maxValue){
					retArray[1] = maxValue;
					// }
				}
