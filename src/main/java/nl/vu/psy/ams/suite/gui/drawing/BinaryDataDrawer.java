	private void recalcAverage() {
		if (sampleTimeInUS > avLength / 10)
			return;
		FileChannel fc = null;
		FileInputStream fis = null;
		int curIndex = 0;
		try {
			fis = new FileInputStream(baseFile);
			fc = fis.getChannel();
			ByteBuffer bb = ByteBuffer.allocate(1000000);
			IntBuffer sb = bb.asIntBuffer();
			long fs = baseFile.length();
			int nRead = 0;
			int nSRead;
			int[] buffer = new int[bb.limit() / 4];
			double curSum = 0;
			int nInSum = 0;
			int nIn60Sec = (int) (avLength / sampleTimeInUS);
			av = new double[(int) Math.ceil((double) fs / (2 * nIn60Sec))];

			for (long i = 0; i < fs; i += nRead) {
				bb.clear();
				sb.clear();
				nRead = fc.read(bb);
				nSRead = nRead / 4;
				if (nRead < 1)
					break;
				sb.get(buffer, 0, nSRead);
				for (int j = 0; j < nSRead; j++) {
					curSum += buffer[j];
					nInSum++;
					if (nInSum == nIn60Sec) {
						av[curIndex] = curSum / nInSum;
						curIndex++;
						curSum = 0;
						nInSum = 0;
					}
				}
			}
			if (nInSum > 0) {
				av[curIndex] = curSum / nInSum;
				curIndex++;
				curSum = 0;
				nInSum = 0;
			}
		} catch (IOException e) {
			e.printStackTrace();
		} finally {
			if (fc != null) {
				try {
					fc.close();
					fis.close();
				} catch (IOException e) {
					e.printStackTrace();
				}
			}
		}

		double curTime = CurrentOpenData.getInstance().getStartTimeInUS() + avLength / 2;

		double xAr[] = new double[av.length];
		for (int i = 0; i < av.length; i++) {
			xAr[i] = curTime + i * avLength;
		}

	}

	private void refillBuffer(long midPoint, int skipNeeded) {
		totalNumberOfShorts = baseFile.length() / 4;
		long lPos = midPoint - skipNeeded * bufferSize / 2;
		if (lPos < 0)
			lPos = 0;
		long rPos = lPos + bufferSize * skipNeeded;
		totalNumberOfShorts = baseFile.length() / 4;
		if (rPos >= totalNumberOfShorts) {
			rPos = totalNumberOfShorts - 1;
			lPos = rPos - bufferSize * skipNeeded;
			if (lPos < 0)
				lPos = 0;
		}
		nValues = (int) ((rPos - lPos) / skipNeeded);

		File dataFile, fileTicks;
		if (skipNeeded == 1) {
			dataFile = baseFile;
			fileTicks = new File(CurrentOpenData.getInstance().getFilePath(), tickFile + ".bin");
		} else {
			dataFile = new File(new File(baseFile.getParentFile(), "tmp"), name + ".bin-" + skipNeeded);
			fileTicks = new File(new File(baseFile.getParentFile(), "tmp"), tickFile + ".bin-" + skipNeeded);
		}
		if (dataFile.exists()) {
			FileChannel fc = null;
			FileInputStream fis = null;
			try {
				fis = new FileInputStream(dataFile);
				fc = fis.getChannel();
				bb.clear();
				bb.limit(4 * nValues);
				fc.read(bb, (long) (4 * Math.floor(lPos / skipNeeded)));
				buff.clear();
				fc.close();
				fis.close();
				buff.get(buffer, 0, nValues);
				if (isInvert())
					for (int i = 0; i < nValues; i++)
						buffer[i] *= -1;
				if (fileTicks.exists()) {
					fis = new FileInputStream(fileTicks);
					fc = fis.getChannel();
					bb.clear();
					bb.limit(4 * nValues);
					fc.read(bb, (long) (4 * Math.floor(lPos / skipNeeded)));
					buff.clear();
					buff.get(ticks, 0, nValues);
					useTicks = true;
				} else {
					useTicks = false;
				}
			} catch (IOException e) {

			} finally {
				if (fc != null) {
					try {
						fc.close();
						fis.close();
					} catch (IOException e) {
						e.printStackTrace();
					}
				}
			}
			isCalculating = false;
			curSkip = skipNeeded;
			lBuffer = lPos;
			rBuffer = rPos;
			if (lPos < lBuffer || rPos > rBuffer)
				System.out.println("Problem refill buffer BinaryDataDrawer");
		} else {
			for (int i = 0; i < nValues; i++)
				buffer[i] = Integer.MIN_VALUE;
			isCalculating = true;
			curSkip = 1;
			lBuffer = -1;
			rBuffer = -1;
			nValues = 0;
		}
	}

